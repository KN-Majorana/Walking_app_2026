/// アプリの地図モードを表す列挙型
enum MapMode {
  /// ゴースト再生モード（過去の散歩を再生）
  animation,

  /// フォトモード（地図なし。撮影した写真を色ごとに並べ、
  /// 同じ色の写真からコラージュ＝自動配置／自由配置＝を作成できる）
  photo,

  /// マップモード（初期状態は霧。散歩中に通った場所の霧が晴れる。
  /// 色クラスタ／領域は作らない）
  ///
  /// 対戦モードは独立したモードではなく、このマップモードの画面から
  /// 左端スワイプで呼び出す全画面オーバーレイとして表示される。
  map,
}
